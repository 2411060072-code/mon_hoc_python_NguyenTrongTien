# --- TRẢ LỜI CÂU HỎI ---
# Để xây dựng hệ thống "chatbot tư vấn tuyển sinh" hoàn chỉnh, cần kết hợp các thư viện:
# 1. Xử lý ngôn ngữ (Học máy/Học sâu): TensorFlow hoặc PyTorch (xây dựng mô hình AI hiểu và sinh ngôn ngữ), 
#    kết hợp Scikit-learn (phân loại câu hỏi, gom cụm dữ liệu).
# 2. Giao diện để người dùng truy cập: Flask hoặc Django (tạo web/API cho người dùng nhập câu hỏi và nhận trả lời).
# 3. Gọi API/HTTP (tùy chọn): Requests (nếu cần lấy dữ liệu tuyển sinh từ hệ thống bên ngoài).
# (Lưu ý: FastAPI có thể dùng thay Flask/Django nếu cần xử lý API tốc độ cao).